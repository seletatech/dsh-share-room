import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const languages = ['en', 'zh', 'zh-Hant'];
const dictionaries = Object.fromEntries(languages.map(locale => [locale, JSON.parse(readFileSync(root + `locale/${locale}.json`, 'utf8'))]));
const logic = readFileSync(root + 'src/i18n.js', 'utf8');
const shared = `const dictionaries = ${JSON.stringify(dictionaries)};\n` + logic;
writeFileSync(root + 'lib/i18n.js', '// Generated by scripts/build-i18n.mjs\n' + shared);
for (const [source, output] of [['src/client.js', 'lib/client.js'], ['src/guest.js', 'lib/guest/app.js']]) {
  writeFileSync(root + output, '// Generated by scripts/build-i18n.mjs; edit src/ and locale/.\n' + readFileSync(root + source, 'utf8').replace('/* SHARE_ROOM_I18N */', () => shared.replaceAll('export function ', 'function ')));
}
